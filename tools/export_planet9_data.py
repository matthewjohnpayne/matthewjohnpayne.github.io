"""Export the cached results of the science-notebooks notebook
notebooks/planet_nine/planet_nine.ipynb for the interactive page
(src/pages/teaching/planet-nine.astro).

Usage (the science-notebooks Python environment), after running the notebook:
    python tools/export_planet9_data.py ../science-notebooks/notebooks/planet_nine

Writes public/data/planet9/secular.json: snapshots of the anti-aligned ensemble after
3 Gyr with pericentres of 30-80 au (semi-major axis, Delta theta_e, pericentre,
inclination), and the flip map with and without the giant planets.
"""
import glob
import json
import os
import sys

import numpy as np

nb_dir = os.path.abspath(sys.argv[1])
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ens_path = sorted(glob.glob(os.path.join(nb_dir, "cache", "ensemble_*.npz")))[-1]
    z = dict(np.load(ens_path))   # load each array once: indexing an NpzFile re-reads the array every time
    a, t = z["a"], z["t"]
    rp = a[:, None] * (1 - z["e"])
    sel = (t[None, :] > 3.0e9) & (rp > 30) & (rp < 80)
    k, j = np.nonzero(sel)
    pts = [[round(float(a[kk]), 1), round(float(np.degrees(z["dtheta"][kk, jj])), 1), round(float(rp[kk, jj]), 1),
            round(float(np.degrees(z["i"][kk, jj])), 1)] for kk, jj in zip(k, j)]
    out = dict(about="Secular evolution of TNOs under Planet Nine (m9 = 10 Earth masses, a9 = 500 au, e9 = 0.6), from the "
                     "notebook planet_nine.ipynb in science-notebooks, after Li, Hadden, Payne & Holman (2018). "
                     "Generated by tools/export_planet9_data.py.",
               ensemble=dict(n=int(a.size), n_flipped=int((z["i"] > np.pi / 2).any(axis=1).sum()), points=pts))
    fm_path = sorted(glob.glob(os.path.join(nb_dir, "cache", "flipmap_*.npz")))
    if fm_path:
        f = np.load(fm_path[-1])
        conv = lambda g: [[None if v < 0 else int(v) for v in row] for row in g]
        out["flipmap"] = dict(a=f["a"].tolist(), rp=f["rp"].tolist(), flip_j2=conv(f["flip_j2"]), flip_noj2=conv(f["flip_noj2"]))
    dest = os.path.join(root, "public", "data", "planet9")
    os.makedirs(dest, exist_ok=True)
    with open(os.path.join(dest, "secular.json"), "w") as fh:
        json.dump(out, fh, separators=(",", ":"))
    print(f"{len(pts):,} snapshots; wrote {os.path.getsize(os.path.join(dest, 'secular.json')) / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
