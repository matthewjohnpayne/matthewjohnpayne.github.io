"""Export the cached results of the science-notebooks notebook
notebooks/exomoons_wd/exomoons_wd.ipynb for the interactive page
(src/pages/teaching/exomoons.astro).

Usage (the science-notebooks Python environment), after running the notebook:
    python tools/export_exomoons_data.py ../science-notebooks/notebooks/exomoons_wd

Writes public/data/exomoons/encounters.json: for each of PVHG16's six encounters, a
random subset of the notebook's 10,000 moons (a / r_H, e, survived) for the survival
maps, and the survival curve from all 10,000; and, if the notebook's scattering
ensemble is cached, pericentre histories of its planets and freed moons.
"""
import glob
import json
import os
import sys

import numpy as np

nb_dir = os.path.abspath(sys.argv[1])
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, nb_dir)
import exomoons as ex  # noqa: E402

N_SHOW = 3000
BINS = np.logspace(-4, np.log10(0.5), 40)


def main():
    rng = np.random.default_rng(1)
    out = dict(about="Moons through single planet-planet encounters (PVHG16 Table 1 and Figure 4), from the notebook "
                     "exomoons_wd.ipynb in science-notebooks. Generated by tools/export_exomoons_data.py.",
               bins=[float(f"{b:.4g}") for b in BINS], cases={})
    for case in ex.FLYBYS:
        path = os.path.join(nb_dir, "cache", f"flyby_{case}_10000.npz")
        r = np.load(path)
        n = r["a_rH"].size
        pick = rng.choice(n, size=min(N_SHOW, n), replace=False)
        idx = np.digitize(r["a_rH"], BINS) - 1
        curve = [None if np.sum(idx == k) < 20 else round(float(r["bound"][idx == k].mean()), 3) for k in range(len(BINS) - 1)]
        out["cases"][case] = dict(
            n=int(n), survive=round(float(r["bound"].mean()), 4), captured=int(r["captured"].sum()),
            a=[float(f"{v:.4g}") for v in r["a_rH"][pick]], e=[float(f"{v:.3g}") for v in r["e"][pick]],
            bound="".join("1" if b else "0" for b in r["bound"][pick].astype(bool)), curve=curve)
    sc = sorted(glob.glob(os.path.join(nb_dir, "cache", "scatter_*.npz")))
    if sc:
        z = np.load(sc[-1])
        step = max(1, z["t"].size // 400)
        systems = []
        for k in range(z["q"].shape[0]):
            q = z["q"][k][::step]
            mb = z["moon_bound"][k][::step]
            moons = np.where(mb, np.nan, q[:, 4:])
            systems.append(dict(planets=[[None if not np.isfinite(v) else float(f"{v:.4g}") for v in q[:, j]] for j in range(4)],
                                moons=[[None if not np.isfinite(v) else float(f"{v:.4g}") for v in moons[:, j]] for j in range(4)]))
        out["scatter"] = dict(t=[float(f"{v:.4g}") for v in z["t"][::step]], systems=systems)
    dest = os.path.join(root, "public", "data", "exomoons")
    os.makedirs(dest, exist_ok=True)
    with open(os.path.join(dest, "encounters.json"), "w") as f:
        json.dump(out, f, separators=(",", ":"))
    print(f"Wrote {os.path.getsize(os.path.join(dest, 'encounters.json')) / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
