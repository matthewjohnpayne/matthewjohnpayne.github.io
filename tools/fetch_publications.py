#!/usr/bin/env python3
"""Fetch Matthew Payne's refereed publications from NASA ADS.

The query reproduces the ADS search Matthew Payne confirmed selects his
refereed papers: author "Payne, Matthew", 2006 onwards, refereed, astronomy
database, excluding other "Payne, M." authors by their middle initials.
"Payne, Matthew P" (University of Colorado) is excluded in addition.

Each paper becomes one record in src/content/publications/<bibcode>.yaml.
Records are regenerated on every run, except that a hand-set `featured: true`
is kept. Records that no longer match the query are deleted unless featured.

Usage:
    ADS_API_TOKEN=... python3 tools/fetch_publications.py   (standard library only)

Get a token at https://ui.adsabs.harvard.edu/user/settings/token.
"""
import datetime
import json
import os
import pathlib
import re
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "content" / "publications"
META = ROOT / "src" / "data" / "publications-meta.json"

QUERY = 'author:"Payne, Matthew" year:2006-'
EXCLUDED_INITIALS = ["C", "G", "R", "M", "E", "Janie", "Jordan"]
FILTERS = [
    '(database:astronomy OR database:physics) NOT database:"physics"',
    'property:"refereed"',
    "*:* " + " ".join(f'NOT author_facet_hier:"1/Payne, M/Payne, M  {i}"' for i in EXCLUDED_INITIALS)
    + ' NOT author_facet_hier:"1/Payne, M/Payne, Matthew A"'
    + ' NOT author_facet_hier:"1/Payne, M/Payne, Matthew P"',
]
FIELDS = "bibcode,title,author,author_norm,year,pub,volume,page,doi,doctype"
# The public ADS search showing the same list, linked from the Publications page.
UI_URL = "https://ui.adsabs.harvard.edu/search/" + urllib.parse.urlencode(
    {"q": QUERY, "fq": FILTERS, "sort": "date desc, bibcode desc"}, doseq=True)

MAX_AUTHORS = 25  # store this many names; authorCount keeps the full total


def token():
    tok = os.environ.get("ADS_API_TOKEN") or os.environ.get("ADS_DEV_KEY")
    if not tok:
        key = pathlib.Path.home() / ".ads" / "dev_key"
        tok = key.read_text().strip() if key.exists() else None
    if not tok:
        raise SystemExit("Set ADS_API_TOKEN (https://ui.adsabs.harvard.edu/user/settings/token).")
    return tok


def search(tok):
    docs, start = [], 0
    while True:
        params = [("q", QUERY), ("fl", FIELDS), ("rows", "200"), ("start", str(start)),
                  ("sort", "date desc, bibcode desc")] + [("fq", f) for f in FILTERS]
        req = urllib.request.Request(
            "https://api.adsabs.harvard.edu/v1/search/query?" + urllib.parse.urlencode(params),
            headers={"Authorization": f"Bearer {tok}"})
        with urllib.request.urlopen(req, timeout=60) as r:
            res = json.load(r)["response"]
        docs += res["docs"]
        start += len(res["docs"])
        if start >= res["numFound"] or not res["docs"]:
            return docs


def payne_position(doc):
    for i, a in enumerate(doc.get("author_norm", []), 1):
        if a == "Payne, M":
            return i
    return None


def slug(bibcode):
    return re.sub(r"[^A-Za-z0-9]", "", bibcode.replace("&", "and"))


def yaml_value(v):
    # JSON scalars and lists are valid YAML, and quoting avoids YAML's surprises.
    return json.dumps(v, ensure_ascii=False)


def read_featured(path):
    return path.exists() and re.search(r"^featured:\s*true\s*$", path.read_text(), re.M) is not None


def main():
    docs = search(token())
    keep = set()
    for d in docs:
        path = OUT / f"{slug(d['bibcode'])}.yaml"
        keep.add(path.name)
        authors = d.get("author", [])
        rec = {
            "title": (d.get("title") or ["(untitled)"])[0],
            "authors": authors[:MAX_AUTHORS],
            "authorCount": len(authors),
            "authorPosition": payne_position(d),
            "year": int(d["year"]),
            "venue": d.get("pub", ""),
            "volume": d.get("volume"),
            "page": (d.get("page") or [None])[0],
            "doi": (d.get("doi") or [None])[0],
            "bibcode": d["bibcode"],
            "url": f"https://ui.adsabs.harvard.edu/abs/{urllib.parse.quote(d['bibcode'])}/abstract",
            "featured": read_featured(path),
            "source": "ADS",
        }
        lines = ["# Generated by tools/fetch_publications.py from NASA ADS. Only `featured` is kept on regeneration."]
        lines += [f"{k}: {yaml_value(v)}" for k, v in rec.items() if v is not None]
        path.write_text("\n".join(lines) + "\n")

    removed = []
    for path in OUT.glob("[!_]*.yaml"):
        text = path.read_text()
        if path.name not in keep and "fetch_publications.py" in text and not read_featured(path):
            path.unlink()
            removed.append(path.name)

    META.write_text(json.dumps({
        "fetched": datetime.date.today().isoformat(),
        "count": len(docs),
        "query": QUERY,
        "filters": FILTERS,
        "adsUrl": UI_URL,
    }, indent=1, ensure_ascii=False) + "\n")
    print(f"Wrote {len(docs)} records to {OUT}" + (f"; removed {len(removed)}" if removed else ""))


if __name__ == "__main__":
    main()
