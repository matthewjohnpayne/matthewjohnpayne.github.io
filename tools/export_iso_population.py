"""Export the interstellar-object Monte Carlo of the science-notebooks notebook
notebooks/iso_lsst/iso_lsst.ipynb for the interactive page
(src/pages/teaching/interstellar-objects.astro).

Usage (the science-notebooks Python environment):
    python tools/export_iso_population.py ../science-notebooks/notebooks/iso_lsst

Reruns the notebook's default Monte Carlo (one million objects, HSP22's choices,
the same seeds) and writes, for every object that is observable from Rubin on
some night with m <= 24 (for H = 22.4):

  public/data/iso/population.bin  little-endian int16, one row of COLUMNS per object
  public/data/iso/population.json the column scales, the threshold grid and totals

The page combines an absolute magnitude H and a limiting magnitude into one
threshold T = limit - (H - 22.4), on a grid of 0.5 mag, and reads each object's
first observable night at or below T. Saturation at m = 16 is ignored there;
this script reports how many detections that changes.
"""
import json
import os
import sys
from multiprocessing import Pool

import numpy as np

nb_dir = os.path.abspath(sys.argv[1])
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, nb_dir)
import iso  # noqa: E402

N_OBJ, N_CHUNK = 1_000_000, 50
T_EXPORT = np.round(np.arange(16.0, 24.01, 0.5), 2)


def main():
    with Pool(os.cpu_count()) as pool:
        allq, det = iso.run(N_OBJ, N_CHUNK, pool)
    cols = [k for k, T in enumerate(iso.T_GRID) if np.any(np.isclose(T, T_EXPORT))]
    assert len(cols) == len(T_EXPORT)
    first = det["first_T"][:, cols]
    keep = first[:, -1] >= 0                       # observable at m <= 24 on some night
    ids = det["id"][keep]
    scale = dict(t_ca=10, d_min=1e4, v_inf=100, q=1e4, inc=100, b=1000)
    values = dict(t_ca=det["t_ca"][keep], d_min=det["d_min"][keep], v_inf=allq["v_inf"][ids],
                  q=allq["q"][ids], inc=allq["inc"][ids], b=allq["b"][ids])
    table = [first[keep].astype(np.int16)]
    for k, s in scale.items():
        v = np.round(values[k] * s)
        assert v.max() < 32767 and v.min() > -32768, k
        table.append(v.astype(np.int16)[:, None])
    table = np.hstack(table)

    out = os.path.join(root, "public", "data", "iso")
    os.makedirs(out, exist_ok=True)
    table.astype("<i2").tofile(os.path.join(out, "population.bin"))
    reach = [int(np.sum(allq["m_min"] <= T)) for T in T_EXPORT]
    meta = dict(
        about="Interstellar objects detectable by the LSST: the default Monte Carlo of the notebook "
              "iso_lsst.ipynb (science-notebooks), after Hoover, Seligman & Payne (2022). Generated by "
              "tools/export_iso_population.py.",
        n_total=N_OBJ, n_rows=int(keep.sum()), thresholds=T_EXPORT.tolist(),
        columns=[f"first_{T}" for T in T_EXPORT] + list(scale), scale=scale,
        reach_counts=reach,
        exact_detectable_22_4=int(np.sum(det["det_22.4"] >= 0)))
    with open(os.path.join(out, "population.json"), "w") as f:
        json.dump(meta, f, separators=(",", ":"))
    size = os.path.getsize(os.path.join(out, "population.bin"))
    print(f"{keep.sum():,} objects, {table.shape[1]} columns, {size / 1e6:.2f} MB")
    print(f"Detectable at H = 22.4 ignoring saturation: {keep.sum():,}; with saturation at m = 16: "
          f"{meta['exact_detectable_22_4']:,}")


if __name__ == "__main__":
    main()
