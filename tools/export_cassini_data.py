"""Export the six basis signatures of the science-notebooks notebook
notebooks/cassini_planet9/cassini_planet9.ipynb for the interactive page
(src/pages/teaching/cassini-planet-nine.astro), with reference values for
tools/validate_cassini/compare.mjs.

Usage (the science-notebooks Python environment):
    python tools/export_cassini_data.py ../science-notebooks/notebooks/cassini_planet9

Writes public/data/cassini/basis.json: measurement times (decimal years), the post-fit range
signature (metres) for each of the six components of T = I - 3 n n^T at unit tidal parameter
(1 Msun/au^3), Saturn's sky track over the arc, and the nominal Planet Nine orbit of
Batygin & Brown (2016) sampled in true anomaly; and tools/validate_cassini/reference.json.
"""
import json
import os
import sys

import numpy as np

nb_dir = os.path.abspath(sys.argv[1])
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, nb_dir)
os.chdir(nb_dir)
import cassini as cs  # noqa: E402

jd, sat = cs.horizons_vectors("6", "2004-01-01", "2015-01-01", "1 d", "data/saturn_2004_2015.npz")
_, ear = cs.horizons_vectors("399", "2004-01-01", "2015-01-01", "1 d", "data/earth_2004_2015.npz")
eph = cs.Ephemeris(jd, sat, ear)
t_obs = np.loadtxt("data/range_times.csv", comments="#", skiprows=3)
forced, free = cs.responses(eph, t_obs, t_obs[0])
fp = forced @ cs.projector(free).T * cs.AU_M                     # metres per unit k

track = eph.saturn(np.linspace(t_obs[0], t_obs[-1], 60))
nu = np.radians(np.arange(-180, 180, 2))
pos = cs.ecliptic_orbit_position(700, 0.6, np.radians(30), np.radians(113), np.radians(150), nu)
r = np.linalg.norm(pos, axis=1)
radec = lambda v: [round(float(np.degrees(np.arctan2(v[1], v[0])) % 360), 3), round(float(np.degrees(np.arcsin(v[2] / np.linalg.norm(v)))), 3)]
out = dict(about="Basis signatures for the Cassini-ranging model of Holman & Payne (2016), from the notebook cassini_planet9.ipynb "
                 "in science-notebooks. Generated by tools/export_cassini_data.py.",
           sigma=31.95, m_earth=cs.M_EARTH,
           years=[round(float(2004 + (t - cs.JD_2004) / 365.25), 4) for t in t_obs],
           basis=[[float(f"{v:.6g}") for v in row] for row in fp],
           saturn=[radec(v) for v in track],
           nominal=dict(elements="a 700 au, e 0.6, i 30, node 113, arg. peri. 150 (ecliptic; Batygin & Brown 2016)",
                        nu=[int(round(np.degrees(v))) for v in nu], radec=[radec(v) for v in pos], r=[round(float(v), 2) for v in r]))
dest = os.path.join(root, "public", "data", "cassini")
os.makedirs(dest, exist_ok=True)
json.dump(out, open(os.path.join(dest, "basis.json"), "w"), separators=(",", ":"))

ref = {}
for name, ra, dec in [("A", 116.7, 24.6), ("B", 115.5, -45.0), ("C", 42.2, -15.7), ("D", 45.0, -40.2), ("E", 169.8, -57.4)]:
    n = cs.radec_to_unit(np.radians(ra), np.radians(dec))
    ref[name] = dict(ra=ra, dec=dec, dchi2_1e12=float(np.sum(cs.signature(n, 1e-12, forced @ cs.projector(free).T) ** 2) / 31.95**2))
n60 = pos[np.argmin(np.abs(np.degrees(nu) - 60))]
ref["nu60"] = dict(signature=[float(v) for v in cs.signature(n60 / np.linalg.norm(n60), 10 * cs.M_EARTH / np.linalg.norm(n60) ** 3, forced @ cs.projector(free).T)])
json.dump(ref, open(os.path.join(root, "tools", "validate_cassini", "reference.json"), "w"), indent=1)
print(f"Wrote basis.json ({os.path.getsize(os.path.join(dest, 'basis.json')) / 1e3:.0f} kB) and reference.json")
