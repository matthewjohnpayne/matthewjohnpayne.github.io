import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

// One YAML file per record. Files starting with "_" are templates and are ignored.
const pattern = '[^_]*.yaml';

// Notebooks authored by Matthew Payne. The MPC tutorial site is authoritative;
// this site links to it rather than copying notebook content.
const tutorials = defineCollection({
  loader: glob({ pattern, base: './src/content/tutorials' }),
  schema: z.object({
    title: z.string(),
    summary: z.string(),
    topic: z.enum(['science', 'orbits', 'animations', 'iod', 'submission', 'api']),
    url: z.url(),
    tools: z.array(z.string()).default([]),
    // Site-relative path of an interactive adaptation, once one exists.
    interactive: z.string().optional(),
    // Research area of a science notebook, for grouping on the Teaching page.
    area: z.enum(['exoplanets', 'moons', 'solar-system', 'detection']).optional(),
    // Bibcodes of the papers a science notebook reproduces, for links from those papers.
    papers: z.array(z.string()).default([]),
    order: z.number().default(100)
  })
});

// Courses Matthew Payne has written or taught.
const courses = defineCollection({
  loader: glob({ pattern, base: './src/content/courses' }),
  schema: z.object({
    title: z.string(),
    institution: z.string(),
    summary: z.string(),
    topics: z.array(z.string()).default([]),
    repo: z.url().optional(),
    order: z.number().default(100)
  })
});

// Software chosen by Matthew Payne, described in its own words (README or repo description).
const software = defineCollection({
  loader: glob({ pattern, base: './src/content/software' }),
  schema: z.object({
    name: z.string(),
    summary: z.string(),
    repo: z.url(),
    language: z.string().optional(),
    // Further links, such as tutorials or documentation.
    links: z.array(z.object({ label: z.string(), href: z.url() })).default([]),
    featured: z.boolean().default(false),
    // Other spellings used in tutorials' `tools` lists, e.g. mpc-orb.
    aliases: z.array(z.string()).default([]),
    // Bibcodes of papers describing or built on the code, for links in both directions.
    papers: z.array(z.string()).default([]),
    // Site-relative path of an interactive page built on the code.
    interactive: z.string().optional(),
    order: z.number().default(100)
  })
});

// Verified bibliographic records only (e.g. from ADS or ORCID), never guessed.
// Most records are generated by tools/fetch_publications.py.
const publications = defineCollection({
  loader: glob({ pattern, base: './src/content/publications' }),
  schema: z.object({
    title: z.string(),
    authors: z.array(z.string()).min(1),
    authorCount: z.number().int().optional(), // full count when `authors` is truncated
    authorPosition: z.number().int().optional(), // Matthew Payne's place in the author list
    year: z.number().int(),
    venue: z.string(),
    volume: z.string().optional(),
    page: z.string().optional(),
    doi: z.string().optional(),
    bibcode: z.string().optional(),
    url: z.url().optional(),
    featured: z.boolean().default(false),
    source: z.string() // where the record was verified, e.g. "ADS" or "ORCID"
  })
});

// Mentees, and collaborators whose role is described in words. Details come from
// Matthew Payne. Co-authors are listed automatically from src/data/collaborators.json.
const people = defineCollection({
  loader: glob({ pattern, base: './src/content/people' }),
  schema: z.object({
    name: z.string(),
    relationship: z.enum(['mentee', 'collaborator']),
    role: z.string().optional(),
    roleUrl: z.url().optional(),         // links the role text, e.g. to a programme page
    moreRoles: z.array(z.object({        // further lines under the first, e.g. a later fellowship
      role: z.string(), roleUrl: z.url().optional(), period: z.string().optional()
    })).default([]),
    affiliation: z.string().optional(),
    now: z.string().optional(),          // where they are now, shown under the name
    period: z.string().optional(),
    url: z.url().optional(),
    summary: z.string().optional(),
    order: z.number().default(0),        // sort key, newest first (e.g. start year)
    source: z.string().optional()        // where the details came from, e.g. "CV (2021)"
  })
});

// Talks and presentations, one file per talk (see docs/TALKS.md).
const talks = defineCollection({
  loader: glob({ pattern, base: './src/content/talks' }),
  schema: z.object({
    title: z.string(),
    date: z.string().regex(/^\d{4}-\d{2}(-\d{2})?$/),   // YYYY-MM-DD, or YYYY-MM when the day is not known
    event: z.string(),
    location: z.string().optional(),
    kind: z.enum(['conference', 'colloquium', 'agency', 'teaching', 'outreach', 'testimony']),
    presenter: z.string().optional(),     // set when someone else gave the talk (Matthew a co-author)
    note: z.string().optional(),
    materials: z.array(z.object({
      label: z.enum(['Slides (PDF)', 'Slides', 'Poster (PDF)', 'Video', 'Abstract', 'Hearing record', 'Written testimony',
                     // for a record that covers more than one deck
                     'SMUG slides (PDF)', 'DPS slides (PDF)', 'Lecture 1 slides (PDF)', 'Lecture 2 slides (PDF)', 'Lecture 3 slides (PDF)']),
      url: z.url()
    })).default([]),
    source: z.string().optional()         // where the record came from, e.g. the Drive folder name; not shown
  })
});

// Questions and answers for the public (/faq/). Answers are drafts until Matthew approves them;
// every factual statement must be supported by one of the listed sources.
const faq = defineCollection({
  loader: glob({ pattern, base: './src/content/faq' }),
  schema: z.object({
    question: z.string(),
    topic: z.enum(['impacts', 'mpc', 'naming', 'distant', 'interstellar', 'near-earth']),
    level: z.enum(['beginner', 'intermediate', 'advanced']),
    // Paragraphs of plain text; [text](url) makes a link and *text* italic. No HTML.
    answer: z.array(z.string()).min(1),
    sources: z.array(z.object({ label: z.string(), url: z.url() })).min(1),
    // Pages on this site that go further, as site-relative paths.
    related: z.array(z.object({ label: z.string(), href: z.string() })).default([]),
    status: z.enum(['draft', 'approved']).default('draft'),
    checked: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),   // when the sources were last checked
    order: z.number().default(100)
  })
});

// Open problems, each taken from the future-work or open-questions passage of one of
// Matthew Payne's refereed papers. Drafts appear only under `npm run dev`; the built
// site shows an idea once Matthew sets status: approved.
const ideas = defineCollection({
  loader: glob({ pattern, base: './src/content/ideas' }),
  schema: z.object({
    title: z.string(),                   // the question, in a line
    area: z.enum(['exoplanets', 'moons', 'solar-system', 'detection', 'software']),
    paper: z.string(),                   // ADS bibcode of the paper the idea comes from
    citation: z.string(),                // e.g. "Deck, Payne & Holman (2013), ApJ 774, 129"
    section: z.string().optional(),      // where in the paper, e.g. "Section 6, Discussion"
    quote: z.string(),                   // the paper's own words, verbatim
    note: z.string().optional(),         // plain-English context; no new claims
    status: z.enum(['draft', 'approved']).default('draft'),
    order: z.number().default(100)
  })
});

// Short dated notes ("today I learned"). Markdown, one file each. Drafts are not
// built or included in the feed (they appear only under `npm run dev`); Matthew sets
// status: published.
const notes = defineCollection({
  loader: glob({ pattern: '[^_]*.md', base: './src/content/notes' }),
  schema: z.object({
    title: z.string(),
    date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
    tags: z.array(z.string()).default([]),
    summary: z.string(),
    status: z.enum(['draft', 'published']).default('draft'),
    source: z.string().optional()        // where the fact was verified; not shown
  })
});

// Object of the Month: one Markdown file per object, the essay as the body (see _TEMPLATE.md).
// Every factual claim must be supported by an entry in `sources`. The orbit comes from the
// MPC Orbits API via tools/export_object_orbits.py (src/data/objects/<file name>.json).
const objects = defineCollection({
  loader: glob({ pattern: '[^_]*.md', base: './src/content/objects' }),
  schema: z.object({
    name: z.string(),                     // as the MPC writes it, e.g. "(469219) Kamoʻoalewa"
    designation: z.string(),              // passed to the MPC Orbits API
    month: z.string().regex(/^\d{4}-\d{2}$/),   // the month it is featured, YYYY-MM
    summary: z.string(),                  // one or two sentences for teasers
    // Extra view of the orbit: 'earth-corotating' adds the path seen from a frame turning with the Earth.
    // 'outer-resonance', 'hyperbolic' and 'earth-capture' use figures computed once by
    // tools/export_object_figures.py (src/data/objects/<name>-figure.json).
    view: z.enum(['heliocentric', 'earth-corotating', 'outer-resonance', 'hyperbolic', 'earth-capture']).default('heliocentric'),
    resonance: z.tuple([z.number().int(), z.number().int()]).optional(),   // [p, q] for outer-resonance, e.g. [21, 5]
    horizons: z.string().optional(),     // JPL Horizons COMMAND, if the designation alone is ambiguous
    related: z.array(z.object({ label: z.string(), href: z.string() })).default([]),
    papers: z.array(z.string()).default([]),   // bibcodes of Matthew's papers about the object
    sources: z.array(z.object({ label: z.string(), url: z.url() })).min(1),
    reviewed: z.boolean().default(false)  // set to true once Matthew has approved the text
  })
});

export const collections = { tutorials, courses, software, publications, people, talks, faq, ideas, notes, objects };
