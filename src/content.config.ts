import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

// One YAML file per record. Files starting with "_" are templates and are ignored.
const pattern = '[^_]*.yaml';

// Notebooks authored by Matthew Payne. The MPC tutorial site is authoritative;
// this site links to it rather than copying notebook content.
const tutorials = defineCollection({
  loader: glob({ pattern, base: './src/content/tutorials' }),
  schema: z.object({
    title: z.string(),
    summary: z.string(),
    topic: z.enum(['science', 'orbits', 'animations', 'iod', 'submission', 'api']),
    url: z.url(),
    tools: z.array(z.string()).default([]),
    // Site-relative path of an interactive adaptation, once one exists.
    interactive: z.string().optional(),
    order: z.number().default(100)
  })
});

// Courses Matthew Payne has written or taught.
const courses = defineCollection({
  loader: glob({ pattern, base: './src/content/courses' }),
  schema: z.object({
    title: z.string(),
    institution: z.string(),
    summary: z.string(),
    topics: z.array(z.string()).default([]),
    repo: z.url().optional(),
    order: z.number().default(100)
  })
});

// Software chosen by Matthew Payne, described in its own words (README or repo description).
const software = defineCollection({
  loader: glob({ pattern, base: './src/content/software' }),
  schema: z.object({
    name: z.string(),
    summary: z.string(),
    repo: z.url(),
    language: z.string().optional(),
    // Further links, such as tutorials or documentation.
    links: z.array(z.object({ label: z.string(), href: z.url() })).default([]),
    featured: z.boolean().default(false),
    order: z.number().default(100)
  })
});

// Verified bibliographic records only (e.g. from ADS or ORCID), never guessed.
// Most records are generated by tools/fetch_publications.py.
const publications = defineCollection({
  loader: glob({ pattern, base: './src/content/publications' }),
  schema: z.object({
    title: z.string(),
    authors: z.array(z.string()).min(1),
    authorCount: z.number().int().optional(), // full count when `authors` is truncated
    authorPosition: z.number().int().optional(), // Matthew Payne's place in the author list
    year: z.number().int(),
    venue: z.string(),
    volume: z.string().optional(),
    page: z.string().optional(),
    doi: z.string().optional(),
    bibcode: z.string().optional(),
    url: z.url().optional(),
    featured: z.boolean().default(false),
    source: z.string() // where the record was verified, e.g. "ADS" or "ORCID"
  })
});

// Mentees, and collaborators whose role is described in words. Details come from
// Matthew Payne. Co-authors are listed automatically from src/data/collaborators.json.
const people = defineCollection({
  loader: glob({ pattern, base: './src/content/people' }),
  schema: z.object({
    name: z.string(),
    relationship: z.enum(['mentee', 'collaborator']),
    role: z.string().optional(),
    roleUrl: z.url().optional(),         // links the role text, e.g. to a programme page
    moreRoles: z.array(z.object({        // further lines under the first, e.g. a later fellowship
      role: z.string(), roleUrl: z.url().optional(), period: z.string().optional()
    })).default([]),
    affiliation: z.string().optional(),
    period: z.string().optional(),
    url: z.url().optional(),
    summary: z.string().optional(),
    order: z.number().default(0),        // sort key, newest first (e.g. start year)
    source: z.string().optional()        // where the details came from, e.g. "CV (2021)"
  })
});

export const collections = { tutorials, courses, software, publications, people };
